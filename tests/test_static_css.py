"""The pre-built web/static/app.css must style the race-day UI (issue #90).

app.css is generated by Tailwind from the templates (`npm ci && npm run build:css`) and
committed, so the Pi needs no build step and no internet. If someone adds a class to a
template without rebuilding, the element silently renders unstyled. CI's `css` job
rebuilds and fails on any difference; these tests pin the elements that broke before.
"""
import os
import re
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATES = os.path.join(ROOT, "web", "templates")
CSS_PATH = os.path.join(ROOT, "web", "static", "app.css")


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as f:
        return f.read()


def _classes_of(template: str, marker: str, tag: str) -> list[str]:
    """Class tokens of the <tag ...> that contains `marker` (an attribute or its text)."""
    html = _read(os.path.join(TEMPLATES, template))
    idx = html.index(marker)
    start = html.rindex("<" + tag, 0, idx + len(marker))
    opening = html[start:html.index(">", start)]
    m = re.search(r'\bclass="([^"]*)"', opening)
    assert m, f"no class attribute on <{tag}> for {marker!r} in {template}"
    return m.group(1).split()


def _css_escape(cls: str) -> str:
    return "".join(c if re.match(r"[A-Za-z0-9_-]", c) else "\\" + c for c in cls)


class TestPrebuiltCss(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.css = _read(CSS_PATH)

    def assertStyled(self, template: str, marker: str, tag: str):
        missing = [c for c in _classes_of(template, marker, tag)
                   if not re.search(r"\." + re.escape(_css_escape(c)) + r"(?![A-Za-z0-9_\\-])", self.css)]
        self.assertEqual(missing, [], f"{template} {marker!r}: classes missing from app.css "
                                      "(run `npm ci && npm run build:css`)")

    def test_crossing_too_soon_prompt(self):
        self.assertStyled("crossings.html", 'id="tooSoonPrompt"', "div")

    def test_replay_chart_container(self):
        # Chart.js uses maintainAspectRatio: false, so the box needs its own height.
        self.assertStyled("replay.html", "h-[520px]", "div")

    def test_admin_buttons_and_review_list(self):
        self.assertStyled("admin.html", "New Event", "button")
        self.assertStyled("admin.html", 'id="btnFullReset"', "button")
        self.assertStyled("admin.html", 'id="flaggedLapsList"', "div")

    def test_login_page(self):
        self.assertStyled("login.html", 'action="/login"', "form")
        self.assertStyled("login.html", "Log in", "button")


if __name__ == "__main__":
    unittest.main()
